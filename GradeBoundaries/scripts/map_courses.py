#!/usr/bin/env python3
"""Build mapping/course-map.yaml — every hub course slug -> boundary identity.

Joins the hub's committed course registry (snapshot copied to mapping/) to
the boundary families by qualification-code shape:

  4AB1            -> pearson-int-gcse-linear   (subject-level raw totals)
  4XAB1 / 4XMAF.. -> pearson-int-gcse-modular  (units raw+UMS, cash-in UMS)
  YAB11 / WMA01.. -> pearson-ial               (units raw+UMS, cash-in UMS)
  0620/9701/...   -> cie-<code>                (component + per-route thresholds)

The map is operator-checkable YAML, committed — the hub-import builder never
guesses a join at build time.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from gb_common import LANE, MAPPING, fail

SNAPSHOT = MAPPING / "hub-course-registry.snapshot.json"


def family_for(code: str, board: str) -> tuple[str, str | None]:
    if board == "Cambridge International":
        return "cie", code
    if code.startswith("4X"):
        return "pearson-int-gcse-modular", None
    if re.fullmatch(r"4[A-Z]{1,3}\d", code):   # 4CH1, 4MA1, 4SD0, 4EA1...
        return "pearson-int-gcse-linear", None
    if code in ("YMA01", "YBI11", "YCH11", "YPH11", "YFM01"):
        return "pearson-ial", code
    return "unmapped", None


# Subject keys used to join parsed Pearson subject rows (which carry the
# unit-code stem like WCH11 -> "CH11") and CIE parsed dirs (cie-<code>).
def main() -> None:
    reg = SNAPSHOT
    if not reg.exists():
        fail(f"missing {reg} — copy content/courses.json first")
    courses = json.loads(reg.read_text())["courses"]
    lines = [
        "# course-boundary-map — hub slug -> boundary identity (T-GRADE-1)",
        "# Generated by scripts/map_courses.py from the hub course registry",
        "# snapshot; joins checked by scripts/build_hub_import.py. Do not",
        "# hand-edit entries — regenerate or add explicit overrides below.",
        "schema: syllabai.grade-boundaries.course-map/1",
        "courses:",
    ]
    unmapped = []
    for c in sorted(courses, key=lambda x: x["slug"]):
        fam, cie = family_for(c["code"], c.get("board", "Edexcel"))
        ial_cashin = c["code"] if fam == "pearson-ial" else None
        lines.append(f"  - slug: {c['slug']}")
        lines.append(f"    code: \"{c['code']}\"")
        lines.append(f"    board: {c.get('board', 'Edexcel')}")
        lines.append(f"    level: {c['level']}")
        lines.append(f"    subject: {c['subject']}")
        lines.append(f"    family: {fam}")
        if cie:
            lines.append(f"    cieSyllabus: \"{cie}\"")
        if ial_cashin:
            lines.append(f"    ialCashIn: \"{ial_cashin}\"")
        if fam == "unmapped":
            unmapped.append(c["slug"])
    out = MAPPING / "course-map.yaml"
    out.write_text("\n".join(lines) + "\n")
    print(f"course map written: {out} ({len(courses)} courses, "
          f"{len(unmapped)} unmapped)")
    if unmapped:
        print("unmapped slugs:", ", ".join(unmapped))


if __name__ == "__main__":
    main()
