for course, table in D.items():
    adj = json.load(open(f'{OUT}/adjudication-{course}.json'))
    rows = adj['rows']
    idxs = set(range(len(rows)))
    dec = set(table.keys())
    missing = idxs - dec
    assert not missing, f'{course}: rows not judged: {sorted(missing)[:10]}'
    extra = dec - idxs
    assert not extra, f'{course}: decisions reference missing rows: {sorted(extra)[:10]}'
    out_rows, out_rejects = [], list(adj['rejects'])
    for i, r in enumerate(rows):
        d = table[i]
        t = pool[r['video']]['title']
        if d[0] == 'drop':
            out_rejects.append({'video': r['video'], 'reason': 'self-review full-row drop: ' + d[1]})
            continue
        if d[0] == 'keep':
            out_rows.append({'video': r['video'], 'specs': list(r['specs']),
                             'confidence': r['confidence'], 'evidence': r['evidence'],
                             'title': t})
            continue
        _, specs, conf, ev = d
        out_rows.append({'video': r['video'], 'specs': list(specs), 'confidence': conf,
                         'evidence': ev, 'title': t})
    json.dump({'course': course, 'rows': out_rows, 'rejects': out_rejects},
              open(f'{OUT}/judgment-{course}.json', 'w'), indent=1)
    print(f'{course}: judged rows {len(out_rows)} | drops->rejects {len(out_rejects)-len(adj["rejects"])} '
          f'| total rejects {len(out_rejects)}')
