def generic_chain(input_s):
    """Port of genericChain — structural grammar must be consumed before
    prose-wrap; any grammar survivor -> None (never \\text{}-wrap grammar)."""
    s = symbol_pre_map(input_s)
    s = re.sub(r"(?:_\s*){2,}", lambda m: " \\underline{\\quad} ", s)
    s = re.sub(r"\btext\s+(.+?)\s+end text", lambda m: " \\text{%s} " % m.group(1), s)

    def _table(m):
        open_p, body, close_p = m.group(1), m.group(2), m.group(3)
        inner0 = re.sub(r"^\s*row\s+", "", body)
        inner0 = re.sub(r"\s+row\s*$", "", inner0)
        rows = []
        for r in re.split(r"\s+row\s+", inner0):
            r = r.strip()
            if not r:
                continue
            cells = [re.sub(r"\s+", " ", c).strip() for c in re.split(r"\b(?:end\s+)?cell\b", r)]
            cells = [c for c in cells if c]
            if cells:
                rows.append(cells)
        if not rows:
            return m.group(0)
        width = max(len(r) for r in rows)
        b = " \\\\ ".join(" & ".join(r) for r in rows)
        inner = ("\\begin{pmatrix}%s\\end{pmatrix}" % b) if (width == 1 and len(rows) >= 2) \
            else ("\\begin{array}{%s}%s\\end{array}" % ("c" * width, b))
        return " \\left(%s\\right) " % inner if (open_p or close_p) else " %s " % inner

    s = re.sub(r"(open parentheses\s+)?table\s+([\s\S]+?)\s+end table(\s+close parentheses)?", _table, s)

    s = re.sub(r"([A-Za-z])\s+subscript\s+([a-zA-Z0-9]+)", r"\1_{\2}", s)
    s = re.sub(r"([A-Za-z0-9}\)])\s+superscript\s+([a-zA-Z0-9]+)", r"\1^{\2}", s)
    s = re.sub(r"([A-Za-z0-9}\)])\s+to the power of\s+([a-zA-Z0-9]+)(?:\s+end exponent)?", r"\1^{\2}", s)
    for _ in range(4):
        s = re.sub(r"fraction numerator\s+(.+?)\s+over denominator\s+(.+?)\s+end fraction",
                   lambda m: "\\frac{%s}{%s}" % (m.group(1).strip(), m.group(2).strip()), s)
    s = re.sub(r"([A-Za-z])_\{(\d+)\}\s+over\s+([A-Za-z])_\{(\d+)\}",
               lambda m: "\\frac{%s_{%s}}{%s_{%s}}" % (m.group(1), m.group(2), m.group(3), m.group(4)), s)
    for _ in range(4):
        s = re.sub(r"(\w+|\{[^{}]*\})\s+over\s+(\w+|\{[^{}]*\})",
                   lambda m: "\\frac{%s}{%s}" % (m.group(1), m.group(2)), s)
    s = re.sub(r"\bstraight\s+([A-Za-z])(?!\w)", lambda m: " \\mathrm{%s} " % m.group(1), s)
    s = word_to_symbol(s)
    if has_residual_grammar(s):
        return None
    s = re.sub(r"(?<![\\\w])([a-z]{3,})(?![\w}])", lambda m: " \\text{%s} " % m.group(1), s)
    out = re.sub(r"\s+", " ", s).strip()
    if not out or out == input_s.strip():
        return None
    return out


