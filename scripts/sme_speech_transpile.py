    if not (TRIGGER_RE.search(alt) or RES_SPEECH.search(alt)):
        return None
    econ = base_pre_map(alt)
    for v in (cie_pre_map(econ), strip_space_tokens(cie_pre_map(econ))):
        tex = speech_to_tex(v)
        if tex is not None:
            norm = macro_norm(tex)
            if not has_residual_grammar(norm) and _katex_approx_ok(norm):
                return "$" + norm + "$"
    gc = generic_chain(econ)
    if gc is not None:
        gc = macro_norm(gc)
        if not has_residual_grammar(gc) and _katex_approx_ok(gc):
            return "$" + gc + "$"
    pl = cie_plain_collapse(base_pre_map(alt))
    if pl is not None:
        return "`" + pl + "`"
    return None
