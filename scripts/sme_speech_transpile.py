def sub(R, rep, s):
    """Template-safe re.sub: backslash-bearing literal replacements are
    returned verbatim (no template escape processing)."""
    if callable(rep):
        return R.sub(rep, s)
    if "\\" in rep:
        return R.sub(lambda m, _r=rep: _r, s)
    return R.sub(rep, s)


