def _katex_approx_ok(tex):
    """Evidence-derived approximation of the of-record katexOk rung-gate
    (the port has no in-process KaTeX). Each clause = a KaTeX throw class
    proven on the fleet corpus at pin 54c0534 (audit run r0):
      - bare "\\n" (NOT followed by a letter; \\neq/\\ne stay legal) — the
        upstream escaped-blockquote artifact, "undefined control sequence";
      - dangling script base "^"/"_" not followed by {, letter, digit, "\\" —
        "Expected group after _";
      - raw unescaped "$" — "Can't use function '$' in math mode" (the
        genericChain rung carries no dollar-escape; katexOk caught it);
      - double-script adjacency "^{..}^" / "_{..}_" — "Double superscript";
      - combining marks U+0300-U+036F — "no character metrics"/"EOF, got";
      - brace imbalance after stripping \\{ / \\} literals — "Unexpected
        end of input in a macro argument" (unclosed exponent braces);
      - environment imbalance (per-name begin/end counts) — "Mismatch:
        \\begin{array} matched by \\end{gathered}";
      - "&" with no environment at all — "Expected 'EOF', got '&'".
    A span failing here falls through to the next rung exactly as the
    of-record katexOk gate does."""
    if (_KATEX_APPROX_BARE_N.search(tex)
            or _KATEX_APPROX_DANGLING_SCRIPT.search(tex)
            or _KATEX_APPROX_RAW_DOLLAR.search(tex)
            or _KATEX_APPROX_DOUBLE_SCRIPT.search(tex)
            or _KATEX_APPROX_COMBINING.search(tex)):
        return False
    stripped = tex.replace("\\{", "").replace("\\}", "")
    if stripped.count("{") != stripped.count("}"):
        return False
    begins = re.findall(r"\\begin\{([^}]+)\}", tex)
    ends = re.findall(r"\\end\{([^}]+)\}", tex)
    if collections.Counter(begins) != collections.Counter(ends):
        return False
    if _KATEX_APPROX_AMP.search(tex) and not begins:
        return False
    return True


