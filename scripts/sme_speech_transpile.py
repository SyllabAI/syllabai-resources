_IS_WORD = re.compile(r"^[a-zA-Z][\u2019'a-zA-Z]*$")


def _wrap_residual_prose(s):
    """Port of wrapResidualProse — leftover English prose runs -> \\text{};
    prose-dominated no-structure spans -> None (caller keeps original)."""
    tokens = re.split(r"(\s+)", s)
    out = []
    run = []
    wrapped_chars = 0
    all_letter_chars = 0

    def is_prose_word(t):
        return bool(_IS_WORD.match(t)) and (len(t) >= 2 or t in ("a", "A"))

    def flush():
        nonlocal wrapped_chars
        if not run:
            return
        if any(len(w) >= 2 for w in run):
            out.append("\\text{%s}" % " ".join(run))
            wrapped_chars += len(re.sub(r"[^a-zA-Z]", "", " ".join(run)))
        else:
            out.append(" ".join(run))
        del run[:]

    for tok in tokens:
        if is_prose_word(tok):
            run.append(tok)
            continue
        flush()
        out.append(tok)
        stripped = tok.replace("\\text", "")
        all_letter_chars += len(re.findall(r"[a-zA-Z]", stripped))
    flush()
    all_letter_chars += wrapped_chars
    s2 = "".join(out)
    has_math_structure = bool(re.search(r"\\(frac|sqrt|sum|int|lim|vec|bar|cancel|xrightarrow)", s2))
    if not has_math_structure and all_letter_chars > 0 and wrapped_chars / all_letter_chars > 0.5:
        return None
    return s2


def _fixup_arrays_and_dangling_amps(s):
    s = re.sub(r"\\begin\{array\}(\{[^}]*\})((?:(?!\\begin\{)[\s\S])*?)\\end\{gathered\}",
               lambda m: "\\begin{array}%s%s\\end{array}" % (m.group(1), m.group(2)), s)
    s = re.sub(r" &\s*(?=\\\\|\\(?:begin|end)\{)", " ", s)
    return s


def speech_to_tex(raw):
    """Port of speechToTex — returns TeX or None when not confident."""
    s = re.sub(r"\\n> ?", " ", raw)
    s = s.replace("\\n", " ")

    s = re.sub(r"begin (?:mathsize \d+px|inline|display) style", " ", s)
    s = s.replace("end style", " ")

    prev = None
    while prev != s:
        prev = s
        s = FRAC_RE.sub(lambda m: " \\frac{%s}{%s} " % (m.group(1).strip(), m.group(2).strip()), s)
        for R, rep in ORDINAL_ROOTS:
            # NB: template form (group refs) — do NOT route through sub()
            s = R.sub(rep, s)
        s = re.sub(r"up diagonal strike (.+?) end strike", lambda m: " \\cancel{%s} " % m.group(1), s)
        s = re.sub(r"to the power of apostrophe (?=open (?:parentheses|square brackets|curly brackets))", " ^{'} ", s)
        s = re.sub(r"to the power of (.+?) end exponent",
                   lambda m: " ^{%s} " % re.sub(r"'\s+'", "''", m.group(1).strip()), s)
        s = re.sub(r"subscript (.+?) end subscript", lambda m: " _{%s} " % m.group(1).strip(), s)
        s = re.sub(r"superscript (.+?) end superscript", lambda m: " ^{%s} " % m.group(1).strip(), s)
        s = re.sub(r"sum from (.+?) to (.+?) of ", lambda m: " \\sum_{%s}^{%s} " % (m.group(1), m.group(2)), s)
        s = re.sub(r"integral from (.+?) to (.+?) of ", lambda m: " \\int_{%s}^{%s} " % (m.group(1), m.group(2)), s)
        s = re.sub(r"limit as (.+?) (?:rightwards arrow|approaches) (.+?) of ",
                   lambda m: " \\lim_{%s \\to %s} " % (m.group(1), m.group(2)), s)
        s = re.sub(r"\btext (.+?) end text", lambda m: " \\text{%s} " % m.group(1), s)
        s = re.sub(r"n-th root of (.+?) end root", lambda m: " \\sqrt[n]{%s} " % m.group(1), s)

    s = re.sub(r"([a-zA-Z\)]) presubscript (\d+) presuperscript (\d+)", r"\1_{\2}^{\3}", s)
    s = re.sub(r"([a-zA-Z\)]) presuperscript (\d+) presubscript (\d+)", r"\1^{\2}_{\3}", s)
    s = re.sub(r"rightwards arrow with (.+?) on top", lambda m: " \\xrightarrow{%s} " % m.group(1), s)

    s = re.sub(r"((?:bold |straight )?[a-zA-Z0-9\)])\s+with\s+(?:bold |straight )?(bar|dot|hat|tilde)\s+on\s+top",
               lambda m: " \\%s{%s} " % (m.group(2), re.sub(r"\b(?:bold|straight) ", "", m.group(1))), s)
    s = re.sub(r"((?:bold |straight )?[a-zA-Z0-9\)])\s+with\s+(?:bold |straight )?rightwards\s+arrow\s+on\s+top",
               lambda m: " \\vec{%s} " % re.sub(r"\b(?:bold|straight) ", "", m.group(1)), s)
    s = re.sub(r"top enclose ((?:straight |bold )?[a-zA-Z])",
               lambda m: " \\vec{%s} " % re.sub(r"\b(?:straight|bold) ", "", m.group(1)), s)
    s = re.sub(r" with blank (?:below|above)(?: and blank on top)?", " ", s)

    s = ORDINAL_ROOTS_ATOM.sub(_replace_ordinal_root_atom, s)
    s = re.sub(r"up diagonal strike ([a-zA-Z0-9]+)", lambda m: " \\cancel{%s} " % m.group(1), s)
    s = re.sub(r"up diagonal strike (blank|[a-zA-Z0-9.]+)", lambda m: " \\cancel{%s} " % m.group(1), s)
    s = re.sub(r"to the power of (?:bold italic |bold |straight )?apostrophe", " ^{'} ", s)
    s = re.sub(r"to the power of (?:bold italic |bold |straight )?negative (blank|[a-zA-Z0-9.]+)",
               r" ^{-\1} ", s)
    s = re.sub(r"to the power of (?:bold italic |bold |straight )?(blank|[a-zA-Z0-9.]+)",
               lambda m: " ^{%s} " % re.sub(r"^(?:bold italic |bold |straight )", "", m.group(1)), s)
    s = re.sub(r"subscript (?:bold italic |bold |straight )?(blank|[a-zA-Z0-9.]+)",
               lambda m: " _{%s} " % m.group(1), s)
    s = re.sub(r"superscript (?:bold italic |bold |straight )?(blank|[a-zA-Z0-9.]+)",
               lambda m: " ^{%s} " % m.group(1), s)

    s = s.replace("stack sum", " \\sum ")
    s = re.sub(r"sum for blank of", lambda m: " \\sum ", s)
    s = re.sub(r"\bintegral\b", lambda m: " \\int ", s)

    s = re.sub(r"\bcapital (sigma|delta|gamma|omega|theta|lambda|phi|psi|xi|pi|upsilon|epsilon)\b",
               lambda m: m.group(1).capitalize(), s)
    s = re.sub(r"\bstraight ([a-zA-Z]+)\b", lambda m: " \\mathrm{%s} " % m.group(1), s)
    s = re.sub(r"\bbold (?=less|greater|percent|space|equals|plus|minus|times|integral|sum|sin|cos|tan|log|ln|sec|csc|cot)\b", " ", s)
    s = re.sub(r"\bbold italic ([a-zA-Z0-9.]+)\b", lambda m: " \\boldsymbol{%s} " % m.group(1), s)
    s = re.sub(r"\bbold percent sign\b", lambda m: " \\boldsymbol{\\%} ", s)
    s = re.sub(r"\bbold\.?(?=[\s)]|$)", " ", s)
    s = re.sub(r"\bbold ([a-zA-Z0-9.]+)\b", lambda m: " \\boldsymbol{%s} " % m.group(1), s)

    for R, rep in _phrases():
        s = sub(R, rep, s)
    s = re.sub(r"\s+([\^_])\{", r"\1{", s)

    cmds = []

    def _protect(m):
        cmds.append(m.group(0))
        return "\x01" + "\x02" * len(cmds) + "\x03"

    s = re.sub(r"\\[a-zA-Z]+(?:\[[^\]]*\])?(?:\{[^}]*\}){0,2}", _protect, s)

    s = re.sub(
        r"(?<![a-zA-Z0-9.\x01\x02\x03])((?:\x01\x02+\x03|[0-9]+(?:\.[0-9]+)?|[a-zA-Z]+)(?:\^\{[^}]*\})?)"
        r" over "
        r"((?:\x01\x02+\x03|-[0-9.]+|[0-9.]+|[a-zA-Z]+|\([^()]+\))(?:\^\{[^}]*\})?)(?![a-zA-Z0-9.])",
        lambda m: " \\frac{%s}{%s} " % (m.group(1), m.group(2)), s)
    s = re.sub(
        r"(?<![a-zA-Z0-9.\x01\x02\x03])\(([^()]*)\)\^\{([^}]*)\} over "
        r"((?:\x01\x02+\x03|[0-9.]+|[a-zA-Z]+|\([^()]*\))(?:\^\{[^}]*\})?)(?![a-zA-Z0-9.\x03])",
        lambda m: " \\frac{(%s)^{%s}}{%s} " % (m.group(1), m.group(2), m.group(3)), s)

    s = re.sub(r"\x01(\x02+)\x03", lambda m: cmds[len(m.group(1)) - 1], s)

    for g in GREEK:
        s = re.sub(r"\b%s\b" % re.escape(g), lambda m, _g=g: "\\%s " % _g, s)
    for f in FUNCTIONS:
        s = re.sub(r"\b%s\b" % re.escape(f), lambda m, _f=f: "\\%s " % _f, s)

    wrapped = _wrap_residual_prose(s)
    if wrapped is None:
        return None
    s = wrapped

    s = re.sub(r"'\s+'", "''", s)
    s = re.sub(r"(?<!\\)\$", lambda m: "\\$", s)
    s = _fixup_arrays_and_dangling_amps(s)

    s = re.sub(r"[ \t]+", " ", s).strip()
    return s

