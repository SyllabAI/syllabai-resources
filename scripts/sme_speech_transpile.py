def has_residual_grammar(tex):
    if GRAMMAR_RE.search(re.sub(r"\\[a-zA-Z]+", " ", tex)):
        return True
    for m in re.finditer(r"\\text\s*\{([^{}]*)\}", tex):
        if BAD_TEXT_CONTENT.match(m.group(1)):
            return True
    stripped = tex
    stripped = re.sub(r"\\text\s*\{[^{}]*\}", " ", stripped)
    stripped = re.sub(r"\\[a-zA-Z]+", " ", stripped)
    stripped = re.sub(r"\\(?:left|right)?\s*[|()[\]]", " ", stripped)
    return bool(GRAMMAR_RE.search(stripped))


