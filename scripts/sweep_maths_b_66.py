#!/usr/bin/env python3
"""T-OEQ-MATHSB-1 run-003 closing sweep: re-stage ALL 66 maths-B papers fresh
(deterministic pdftotext -layout under the current poppler 25.03.0) and run
the full conversion + G0-G7 gates on every paper. Asserts 66/66 ALL PASS.
Idempotent; the OCR-spliced papers re-splice via prep (their staged txt is
regenerated by the converter's own prep — see prep_ocr_layer_2019mb.py).
"""
import json
import subprocess
import sys
from pathlib import Path

RES = Path("/home/z/my-project/repos/resources")
U = Path("/home/z/my-project/upload")
COURSE_DIR = RES / "Official-ExamQuestion" / "igcse-maths-b-16"
BASE = ("https://raw.githubusercontent.com/SyllabAI/syllabai-pastpapers/main/"
        "past-papers/pearson-edexcel/international-gcse/mathematics-b/4mb1/past-papers")
TOK = [l.split("=", 1)[1] for l in open("/home/z/my-project/.creds/syllabai.env")
       if l.startswith("GITHUB_PAT=")][0].strip()

# the OCR-spliced papers: their staged txt must be re-prepared AFTER re-extraction
OCR_PAPERS = {("2019-01", "01"), ("2019-01", "01R")}


def papers():
    out = []
    for series_dir in sorted(COURSE_DIR.iterdir()):
        if not series_dir.is_dir():
            continue
        for paper_dir in sorted(series_dir.iterdir()):
            if paper_dir.is_dir():
                variant = paper_dir.name.split("MB1-")[1]
                out.append((series_dir.name, variant))
    return out


def fetch(series, variant, kind):
    name = {"qp": f"official-4MB1-{variant}-{series}-qp.pdf",
            "ms": f"official-4MB1-{variant}-{series}-ms.pdf",
            "manifest": f"manifest-{series}-{variant}.yaml"}[kind]
    dest = U / name
    if dest.exists() and dest.stat().st_size > 0:
        return True
    url = f"{BASE}/{series}/4MB1-{variant}/{kind}.pdf" if kind != "manifest" \
        else f"{BASE}/{series}/4MB1-{variant}/manifest.yaml"
    r = subprocess.run(["curl", "-sfL", "-H", f"Authorization: token {TOK}",
                        url, "-o", str(dest), "-w", "%{http_code}"],
                       capture_output=True, text=True)
    return r.stdout.strip() == "200" and dest.stat().st_size > 0


def main():
    allp = papers()
    print(f"papers of record: {len(allp)}")
    missing_src = []
    for series, variant in allp:
        for kind in ("qp", "ms", "manifest"):
            if not fetch(series, variant, kind):
                missing_src.append((series, variant, kind))
    if missing_src:
        sys.exit(f"missing sources: {missing_src}")

    # fresh txt extraction for every paper (the poppler-25.03.0 corpus basis)
    for series, variant in allp:
        for kind in ("qp", "ms"):
            pdf = U / f"official-4MB1-{variant}-{series}-{kind}.pdf"
            txt = U / f"official-{series}-{variant}-{kind}.txt"
            subprocess.run(["pdftotext", "-layout", str(pdf), str(txt)], check=True)
    # re-splice the OCR layers on top of the fresh extractions
    subprocess.run([sys.executable, str(RES / "scripts" / "prep_ocr_layer_2019mb.py")], check=True)

    # full sweep
    results = []
    for series, variant in allp:
        r = subprocess.run([sys.executable, str(RES / "scripts" / "official_examq_extract.py"),
                            "--course", "igcse-maths-b-16",
                            "--series", series, "--paper", variant],
                           capture_output=True, text=True, timeout=300)
        vr = COURSE_DIR / series / f"4MB1-{variant}" / "validation-report.json"
        try:
            rep = json.loads(vr.read_text())
            bad = [g["gate"] for g in rep["gates"] if g["status"] not in ("PASS", "PASS-INFO", "SKIP")]
        except Exception as e:  # noqa: BLE001
            bad = [f"REPORT-UNREADABLE {e}"]
        results.append({"paper": f"{series}/4MB1-{variant}", "exit": r.returncode, "bad_gates": bad})
        flag = "PASS" if (r.returncode == 0 and not bad) else f"FAIL {bad}"
        print(f"  {series} 4MB1-{variant}: {flag}")
    n_ok = sum(1 for r in results if r["exit"] == 0 and not r["bad_gates"])
    print(f"SWEEP VERDICT: {n_ok}/{len(results)} ALL-GATES-PASS")
    json.dump(results, open(U / f"sweep-{len(allp)}.json", "w"), indent=1)
    sys.exit(0 if n_ok == len(results) else 1)


if __name__ == "__main__":
    main()
