# NOTE: the fixture decision-record edges carry an extra key
# (`operator_decision`) that the generated graph file intentionally omits —
# operator_decision blocks live decisions-side only and are never emitted
# into graph/*.yaml (architecture §7). The consistency check only compares
# identities + validation_status, so the fixture is consistent by design.


def apply_hunks(old_text: str, hunks: list) -> str:
    old = old_text.splitlines(keepends=True)
    out, pos = [], 0
    for h in hunks:
        m = re.match(r"@@ -(\d+),(\d+) \+\d+,\d+ @@", h[0])
        a_start, a_count = int(m.group(1)), int(m.group(2))
        out += old[pos:a_start - 1]
        pos = a_start - 1
        for l in h[1:]:
            if l.startswith("+") or l.startswith(" "):
                out.append(l[1:])
        pos += a_count
    out += old[pos:]
    return "".join(out)


def run_cli(argv, base: Path):
    import contextlib
    import io
    old_repo = T.REPO
    T.REPO = base
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            rc = T.main(argv)
    finally:
        T.REPO = old_repo
    return (rc if isinstance(rc, int) else 0), buf.getvalue()


def main() -> int:
    print("c11_diff_review_test")
    tmp = Path(tempfile.mkdtemp(prefix="c11diffreview-"))
    try:
        base = tmp / "fx"
        base.mkdir()
        make_fixture(base)

        st = T.load_state(base)
        print(" fixture state")
        check("P3 roundtrip guard", (T.roundtrip_guard(st), True)[1])
        check("P2 consistency silent", st["failures"] == [],
              str(st["failures"]))
        fp1, fp2 = T.fingerprint(st), T.fingerprint(T.load_state(base))
        check("P2 fingerprint stable", fp1 == fp2)

        pend = T.pending_items(st)
        act = T.actionable_edges(st)
        check("P1 pending == 2 (clean+PENDING)", len(pend) == 2, str(len(pend)))
        clean = [i for i in pend if not i["flag"]]
        flagged = [i for i in pend if i["flag"] == "PENDING"]
        check("P1 one clean one flagged", len(clean) == 1 and len(flagged) == 1)
        check("P1 HOLD edge not actionable",
              len(act) == 3 and all(a["flag"] == "DECIDED"
                                    for a in act if not a["actionable"]))
        check("P1 nodes listed", len(T.node_items(st)) == 2)

        ident = clean[0]["identity"]
        by, date = "operator", "2026-09-12"
        eh, mh = T.edge_hunks(st, ident, by, date)
        ebody = "".join(eh)
        check("P4 edge hunk removes SUGGESTED",
              "-  validation_status: SUGGESTED\n" in ebody)
        check("P4 edge hunk adds the 3-line §18 change",
              "+  validation_status: HUMAN_VALIDATED\n" in ebody
              and f"+  validated_by: {by}\n" in ebody
              and f"+  validated_date: '{date}'\n" in ebody)
        check("P4 keys land at validation_status position",
              ebody.index("+  validation_status:") <
              ebody.index("+  validated_by:") <
              ebody.index("+  validated_date:") <
              ebody.index("   version: 1"))
        mbody = "".join(mh)
        check("P4 meta hunk adds the 3-line file-level change",
              f"+    promoted_edges: 1\n" in mbody
              and f"+    human_validated_edges: 1\n" in mbody
              and "+  promotion_record: scripts/c11_promotions.yaml\n"
                  in mbody)

        old, new = T.simulate_promotion(st, [ident], by, date)
        check("P5 hunk application == full simulation",
              apply_hunks(old, [mh, eh]) == new)  # file order: meta first

        snap = (base / "graph" / "concept_edges.yaml").read_text()

        rc, out = run_cli(["approve", ident, "--by", by, "--date", date,
                           "--dry-run"], base)
        check("P6 dry-run exit 0", rc == 0)
        check("P6 dry-run prints the exact c11_promote command",
              "c11_promote.py --edge " + ident in out)
        check("P6 dry-run writes nothing",
              not (base / "scripts" / "c11_promotions.yaml").exists()
              and (base / "graph" / "concept_edges.yaml").read_text() == snap)

        rc, out = run_cli(["approve", "--all", "--by", by, "--date", date,
                           "--dry-run"], base)
        check("P7 approve-all excludes PENDING by default",
              "4CH1-CON-A REQUIRES_PREREQUISITE 4CH1-CON-C" not in out
              and "c11_promote.py --edge 4CH1-CON-A REQUIRES_PREREQUISITE "
                  "4CH1-CON-B" in out)
        rc, out = run_cli(["approve", "--all", "--include-pending", "--by", by,
                           "--date", date, "--dry-run"], base)
        check("P7 --include-pending selects the PENDING edge",
              "--edge 4CH1-CON-A REQUIRES_PREREQUISITE 4CH1-CON-C" in out)

        rc, out = run_cli(["approve", "--except", ident, "--by", by,
                           "--date", date, "--dry-run"], base)
        check("P8 --except removes the listed identity",
              ident not in out.split("c11_promote.py")[1])

        # --- negatives (fail closed, nothing written) -----------------------
        print(" fail-closed negatives")
        N = [("N1 unknown identity",
              ["approve", "4CH1-CON-NOPE REQUIRES_PREREQUISITE 4CH1-CON-B",
               "--by", by, "--dry-run"]),
             ("N2 out-of-range index", ["approve", "99", "--by", by,
                                        "--dry-run"]),
             ("N3 PART_OF refused",
              ["approve", "4CH1-CON-X PART_OF 4CH1-1.27", "--by", by,
               "--dry-run"]),
             ("N4 held candidate refused",
              ["approve", "4CH1-CON-A REQUIRES_PREREQUISITE 4CH1-CON-LAW",
               "--by", by, "--dry-run"]),
             ("N5 REVIEW_REQUIRED refused",
              ["approve", "4CH1-CON-G REQUIRES_PREREQUISITE 4CH1-CON-LAW",
               "--by", by, "--dry-run"]),
             ("N6 AI --by rejected",
              ["approve", ident, "--by", "Super Z", "--dry-run"]),
             ("N7 missing --by", ["approve", ident, "--dry-run"]),
             ("N8 bad --date",
              ["approve", ident, "--by", by, "--date", "12-09-2026",
               "--dry-run"])]
        for name, argv in N:
            expect_exit(name, 1, run_cli, argv, base)
        # N5 must resolve to the REVIEW_REQUIRED identity, not 'unknown'
        st2 = T.load_state(base)
        rr = [i for i in T.actionable_edges(st2) if i["flag"] == "DECIDED"
              and i["edge"]["validation_status"] == "REVIEW_REQUIRED"]
        check("N5 REVIEW_REQUIRED still pending-classified", len(rr) == 1)
        check("N9/N10 prerequisites still intact",
              not (base / "scripts" / "c11_promotions.yaml").exists()
              and (base / "graph" / "concept_edges.yaml").read_text() == snap)

        # N9: real (non-dry) approve without the ratifying bundle
        expect_exit("N9 real approve without bundle refused", 1, run_cli,
                    ["approve", ident, "--by", by, "--date", date], base)

        # N10: hand-edited graph (byte-level) -> roundtrip guard refusal
        (base / "graph" / "concept_edges.yaml").write_text(
            snap + "# stray hand-edit\n", encoding="utf-8")
        expect_exit("N10 hand-edited graph refused", 1, run_cli,
                    ["approve", ident, "--by", by, "--date", date,
                     "--dry-run"], base)
        (base / "graph" / "concept_edges.yaml").write_text(snap,
                                                           encoding="utf-8")

        # N11: validation_status drift decisions <-> graph
        idx = snap.index("\nmeta:\n")
        doc = yaml.safe_load(snap[idx + 1:])   # body incl. the `meta:` line
        for e in doc["edges"]:
            if (e["source"], e["relation"], e["target"]) == \
                    ("4CH1-CON-A", "REQUIRES_PREREQUISITE", "4CH1-CON-B"):
                e["validation_status"] = "REVIEW_REQUIRED"
        (base / "graph" / "concept_edges.yaml").write_text(
            snap[:idx + 1] + yaml.safe_dump(doc, **T.DUMP_KW),
            encoding="utf-8")
        expect_exit("N11 status drift refused", 1, run_cli,
                    ["approve", ident, "--by", by, "--date", date,
                     "--dry-run"], base)
        (base / "graph" / "concept_edges.yaml").write_text(snap,
                                                           encoding="utf-8")

        check("N* negatives wrote nothing",
              not (base / "scripts" / "c11_promotions.yaml").exists()
              and (base / "graph" / "concept_edges.yaml").read_text() == snap)

        # --- real-repo read-only smoke --------------------------------------
        print(" real-repo smoke (read-only)")
        r = subprocess.run([sys.executable, str(HERE / "c11_diff_review.py"),
                            "list"], cwd=T.REPO, capture_output=True, text=True)
        check("R1 list exits 0", r.returncode == 0, r.stderr[:200])
        # session-48 expectation: the batch-1 operator gate is SETTLED —
        # the "CONFIRM all" verdict round (scripts/c11_batch1_verdicts.yaml)
        # was applied through §18 (28 batch-1 edges promoted, store total
        # 56). The actionable surface is now empty; the 5 not-actionable
        # rows = 3 pilot operator HOLDs + the pilot RR + the settled
        # batch-1 RR (HOLD_REVIEW_REQUIRED).
        check("R1 reports 0 actionable / 5 not-actionable / 56 promotions",
              "actionable: 0  (clean 0 / pending-flagged 0)" in r.stdout
              and "not-actionable: 5" in r.stdout
              and "promo_count=56" in r.stdout)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    print()
    if FAILS:
        print(f"FAIL: {len(FAILS)} test(s): {FAILS}")
        return 1
    print("ALL PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
