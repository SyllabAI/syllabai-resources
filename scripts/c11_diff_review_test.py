def expect_exit(name: str, code: int, fn, *a, **kw):
    try:
        rc = fn(*a, **kw)
        got = rc if isinstance(rc, int) else 0
    except SystemExit as e:
        got = e.code if isinstance(e.code, int) else (1 if e.code else 0)
    check(name, got == code, f"(expected exit {code}, got {got})")


